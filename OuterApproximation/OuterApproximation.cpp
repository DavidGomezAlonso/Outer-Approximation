class variablesDual {
    const double gamma05;
public:
    const Datos& datos;
    GRBModel problemaDual;
    vector<GRBVar> alpha;
    vector<GRBVar> omega;
    vector<GRBVar> beta_l;
    vector<GRBVar> beta_u;
    GRBVar         lambda;
    GRBQuadExpr obj;
    variablesDual(GRBEnv& env, const Datos& datos) : datos(datos), problemaDual(env), alpha(datos.r), omega(datos.n), beta_l(datos.m), beta_u(datos.m), gamma05(datos.gamma * 0.5) { 
        problemaDual.set(GRB_IntParam_OutputFlag, 0);
        for (int i = 0; i < datos.r; i++) {
            alpha[i] = problemaDual.addVar(-GRB_INFINITY, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "alpha_" + to_string(i));
        }
        for (int i = 0; i < datos.n; i++) {
            omega[i] = problemaDual.addVar(-GRB_INFINITY, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "omega_" + to_string(i));
        }
        for (int i = 0; i < datos.m; i++) {
            beta_l[i] = problemaDual.addVar(0.0, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "Beta_l_" + to_string(i));
            beta_u[i] = problemaDual.addVar(0.0, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "Beta_u_" + to_string(i));
        }
        lambda = problemaDual.addVar(-GRB_INFINITY, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "lambda");
        problemaDual.update();
        // Funcion objetivo - Se crea una unica vez 
        
            
            // -1/2 alfa^T alfa
            for (int i = 0; i < datos.r; i++) {
                obj -= 0.5 * alpha[i] * alpha[i];
            }
            // y^T alpha
            for (int i = 0; i < datos.r; i++) {
                obj += datos.y[i] * alpha[i];
            }
            // Beta_l^T l
            for (int i = 0; i < datos.m; i++) {
                obj += beta_l[i] * datos.l[i];
            }
            // Beta_u^T u
            for (int i = 0; i < datos.m; i++) {
                obj -= beta_u[i] * datos.u[i];
            }
            // lambda
            obj += lambda;
         
        
        // Restricciones
        for (int i = 0; i < datos.n; i++) {
            GRBLinExpr rest;

            // X^T alpha
            for (int j = 0; j < datos.r; j++) {
                rest += datos.X[j][i] * alpha[j];
            }
            // A^T (Beta_l-Beta_u)
            for (int j = 0; j < datos.m; j++) {
                rest += datos.A[j][i] * (beta_l[j] - beta_u[j]);
            }
            // lambda e
            rest += lambda;
            // - d
            rest -= datos.d[i];

            // Anadimos restricciones para omega[i]
            problemaDual.addConstr(omega[i] >= rest, "omega_restr_" + to_string(i));

        }
        

       
    }
    solProblemaDual solve(const vector<double>& z) {
        solProblemaDual resultado;
        resultado.factible = false;
        resultado.omega.assign(datos.n, 0.0);
        resultado.grad.assign(datos.n, 0.0);
        // - gamma/2 sum(zi wi^2)
        GRBQuadExpr tempZ;
        for (int i = 0; i < datos.n; i++) {
            if (z[i] > 0.5) {               // z es vector double. Para evitar problemas ponemos >0.5 mas que seguro que !=0
                tempZ -= gamma05 * omega[i] * omega[i]; 
            }
        }
        tempZ+=obj;
        problemaDual.setObjective(tempZ, GRB_MAXIMIZE);
        problemaDual.optimize();
        int status = problemaDual.get(GRB_IntAttr_Status);
        if (status == GRB_OPTIMAL || status == GRB_SUBOPTIMAL) {
            // Problema es factible
            resultado.factible = true;
            // Obtenemos valor funcion objetivo
            resultado.f_z = problemaDual.get(GRB_DoubleAttr_ObjVal);
            // Extraemos valor variables
            for (int i = 0; i < datos.n; i++) {
                resultado.omega[i] = omega[i].get(GRB_DoubleAttr_X);
                resultado.grad[i] = -gamma05 * resultado.omega[i] * resultado.omega[i];  
             
            }


        }
        else {
            resultado.f_z = 1e30;   // Si no se alcanza solucion optima o factible -> f(z) lo establecemos inf (o un numero muy grande en nuestro caso)
        }
        return resultado;
       
    }





};
class variablesMin {
    const int n;
    const int k;
    int numCorte;
public:
    GRBModel ProblemaTheta;
    GRBVar theta;
    vector<GRBVar> z;
    variablesMin(GRBEnv& env, const Datos& datos) : ProblemaTheta(env),z(datos.n), n(datos.n),numCorte(0),k(datos.k) {
        ProblemaTheta.set(GRB_IntParam_OutputFlag, 0);
        // Declaramos variables
        theta = ProblemaTheta.addVar(-GRB_INFINITY, GRB_INFINITY, 0.0, GRB_CONTINUOUS, "theta");
        for (int i = 0; i < n; i++) {
            z[i] = ProblemaTheta.addVar(0.0, 1.0, 0.0, GRB_BINARY, "z_" + to_string(i));
        }
        ProblemaTheta.update();
        GRBLinExpr obj;    
        obj += theta;
        ProblemaTheta.setObjective(obj, GRB_MINIMIZE);
        // Restricciones
        GRBLinExpr cardinalidad;
        for (int i = 0; i < n; i++) {
            cardinalidad += z[i];
        }
        ProblemaTheta.addConstr(cardinalidad <= k, "cardinalidad");

    }
    solProblemaMin Solve(solProblemaDual& dual, solProblemaMin& min) {       
        numCorte += 1;  //  Para llevar recuento de numero de cortes
        solProblemaMin minNueva(min.z,min.theta);                           
        GRBLinExpr restr;
        restr += dual.f_z;
        for (int i = 0; i < n; i++) {                                       
            restr += dual.grad[i] * z[i];
            restr -= dual.grad[i] * min.z[i];

        }
        ProblemaTheta.addConstr(theta >= restr, "Corte_OA_" + to_string(numCorte));
        ProblemaTheta.optimize();
        int status = ProblemaTheta.get(GRB_IntAttr_Status);
        if (status == GRB_OPTIMAL || status == GRB_SUBOPTIMAL) {
            minNueva.theta = ProblemaTheta.get(GRB_DoubleAttr_ObjVal);
            for (int i = 0; i < n; i++) {
                minNueva.z[i] = (z[i].get(GRB_DoubleAttr_X) > 0.5) ? 1.0 : 0.0;
            }
            min.factible = 1;

        }
        else {
            cout << "Problema Min Theta infactible\n";

        }
        return minNueva;

        
        

    }
    




};
class AlgoritmoOA {
public:
    const Datos& datos;
   
    variablesDual dual;
    variablesMin min;
    AlgoritmoOA(GRBEnv& env,const Datos& datos): datos(datos), dual(env,datos), min(env,datos) {
    }    
    solOA solve(vector<double>& zinit,double epsilon, int iterMax){
        solOA sol(datos, iterMax);
        
        sol.zOpt=zinit;
        solProblemaMin solMin(zinit);
       
        std::cout << "\n"
            << std::setw(5) << "Iter"
            << std::setw(16) << "f(z) [UB]"
            << std::setw(16) << "theta [LB]"
            << std::setw(12) << "Gap"
            << "\n"
            << std::string(49, '-') << "\n";
        for (int t = 1; t <= iterMax; t++) {
        
            
            // --- Paso 1: Evaluar f(z_actual) ---
            solProblemaDual solDual;

            try{    

                solDual = dual.solve(solMin.z);
            }
            catch (GRBException& e) {
                cerr << "[Problema Dual] Gurobi error  " << e.getErrorCode() << ": " << e.getMessage() << "\n";
                solDual.f_z = 1e30;


            }
            
            if (solDual.factible && solDual.f_z < sol.fOpt) {
                sol.fOpt = solDual.f_z;
                sol.zOpt= solMin.z;
                sol.omega = solDual.omega;


            }
       
            sol.theta_hist.push_back(solMin.theta);
            sol.fz_hist.push_back(solDual.f_z);

            double gap = (sol.fOpt < 1e29) ? (sol.fOpt - solMin.theta) : 1e30;

            std::cout << std::setw(5) << t
                << std::setw(16) << std::setprecision(6) << sol.fOpt
                << std::setw(16) << solMin.theta
                << std::setw(12) << gap
                << "\n";
            // ---- Criterio de parada ----
            if (gap <= epsilon) {
                cout << "Convergencia en iteracion " << t << "\n" << "|f(z)-theta|<=" << std::fixed << epsilon << "\n";
                break;
            }
            // ---- Paso 2: Resolver problema min theta ---

            try{        
                solMin = min.Solve(solDual, solMin);
            }
            catch (GRBException& e) {
                cerr << "[Problema Theta] Gurobi error " << e.getErrorCode() << ": " << e.getMessage() << "\n";
            }
            if (t == iterMax) {
                cout << "Maximo iteraciones alcanzado" << "\n";
            }

        }
        return sol;



    }








};

